import assert from 'node:assert/strict';
import { createCmsPermissions, hasCmsEntryPermission } from '../shared/cmsPermissions.js';
import { changedAliasBodyFields, preserveAliasStoredBody } from '../shared/pageBodyOwnership.js';
const user = permission => ({ role:'editor', permissions:{ ...createCmsPermissions(false), [permission]:true } });
const owner = { collection:'pages', entry_key:'training-division', data_en:{sectionKey:'divisions'} };
const school = { ...owner, entry_key:'school-of-geo-informatics-division1' };
const other = { ...owner, entry_key:'earth-resources-division' };
assert.equal(hasCmsEntryPermission(user('academics'),'pages',owner),true);
assert.equal(hasCmsEntryPermission(user('academics'),'pages',school),true);
assert.equal(hasCmsEntryPermission(user('academics'),'pages',other),false);
assert.equal(hasCmsEntryPermission(user('academics'),'divisions',owner),false);
assert.equal(hasCmsEntryPermission(user('standalone_pages'),'pages',owner),false);
assert.equal(hasCmsEntryPermission(user('standalone_pages'),'pages',{dataEn:{sectionKey:'standalone'}}),true);
assert.equal(hasCmsEntryPermission(user('divisions'),'pages',other),true);
const alias={entryKey:'training-division-',dataEn:{html:'',blocks:[{type:'paragraph',text:'Stored'}],sectionContentVersion:2},dataHi:{html:'पुराना'}};
assert.deepEqual(changedAliasBodyFields(alias,{dataEn:{title:'New local heading'}}),[]);
assert.deepEqual(changedAliasBodyFields(alias,{dataEn:{blocks:[{type:'paragraph',text:'Different'}]}}),['dataEn.blocks']);
assert.deepEqual(changedAliasBodyFields(alias,{dataHi:{html:'नया'}}),['dataHi.html']);
const preserved=preserveAliasStoredBody(alias.dataEn,{title:'New heading',blocks:[],html:''});
assert.equal(preserved.title,'New heading');
assert.deepEqual(preserved.blocks,alias.dataEn.blocks);
assert.equal(preserved.sectionContentVersion,2);
console.log('Shared course permissions and immutable alias-body validation passed; unrelated divisions remain denied.');
